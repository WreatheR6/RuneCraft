"""Writes src/test/resources/osrs/monster_aggression.tsv (round 42) and the rows of
src/main/java/com/runecraft/osrs/data/MonsterAggression.java: the monster infobox "aggressive" field and the max hit of every
RuneCraft creature with a wiki counterpart (the rows of monster_traits.tsv, matched by wiki name and version), from
Kiyogitpy/osrs-wiki-data. Usage:
    python3 -I monster_aggression.py <osrs-wiki-data> <monster_traits.tsv> <out.tsv> [<MonsterAggression.java>]
A plain "Yes"/"No" is definite; conditional text ("Yes, unless wearing a Bandos-affiliated item", "Varies", "N/A") is kept in
wiki_text and left blank in aggressive, so the creature keeps its own flag."""
import csv
import os
import re
import sys

WIKI, TRAITS, OUT = sys.argv[1], sys.argv[2], sys.argv[3]
JAVA = sys.argv[4] if len(sys.argv) > 4 else None

index = {}
with open(os.path.join(WIKI, 'index.tsv'), encoding='utf-8') as f:
    next(f)
    for line in f:
        parts = line.rstrip('\n').split('\t')
        if len(parts) >= 2:
            index[parts[0]] = parts[1]


def page(title, depth=0):
    p = index.get(title) or index.get(title[:1].upper() + title[1:])
    if p is None:
        return None
    with open(os.path.join(WIKI, p), encoding='utf-8') as f:
        text = f.read()
    m = re.match(r'\s*#REDIRECT\s*\[\[([^\]#|]+)', text, re.I)
    if m and depth < 3:
        return page(m.group(1).strip(), depth + 1)
    return text


def infoboxes(text):
    out = []
    for m in re.finditer(r'\{\{Infobox Monster', text):
        depth = 0
        i = m.start()
        while i < len(text):
            if text.startswith('{{', i):
                depth += 1
                i += 2
                continue
            if text.startswith('}}', i):
                depth -= 1
                i += 2
                if depth == 0:
                    break
                continue
            i += 1
        fields = {}
        for fm in re.finditer(r'^\|\s*([a-z0-9 _]+?)\s*=(.*)$', text[m.start():i], re.M):
            fields[fm.group(1).strip()] = fm.group(2).strip()
        out.append(fields)
    return out


def norm(v):
    v = re.sub(r'<[^>]+>', '', v)
    v = re.sub(r'\[\[(?:[^\]|]*\|)?([^\]]*)\]\]', r'\1', v)
    return v.replace('\t', ' ').strip()


def field(box, name, idx):
    if idx and (name + idx) in box:
        return norm(box[name + idx])
    return norm(box.get(name, ''))


rows = []
with open(TRAITS, encoding='utf-8') as f:
    reader = csv.DictReader([l for l in f if not l.startswith('#')], delimiter='\t')
    for r in reader:
        text = page(r['wiki_name'])
        aggressive, max_hit, raw = '', '', ''
        for box in infoboxes(text or ''):
            idx = None
            if r['version']:
                for k, v in box.items():
                    m = re.fullmatch(r'version(\d+)', k)
                    if m and norm(v) == r['version']:
                        idx = m.group(1)
                if idx is None and any(re.fullmatch(r'version\d+', k) for k in box):
                    continue
            raw = field(box, 'aggressive', idx)
            low = raw.lower()
            aggressive = 'yes' if low == 'yes' else 'no' if low == 'no' else ''
            hit = field(box, 'max hit', idx)
            max_hit = hit if re.fullmatch(r'\d+', hit) else ''
            break
        rows.append((r['key'], r['wiki_name'], r['version'], r['level'], aggressive, max_hit, raw))

with open(OUT, 'w', encoding='utf-8') as f:
    f.write('# OSRS aggressiveness and max hit of every RuneCraft creature with a wiki counterpart (the rows of monster_traits.tsv):\n')
    f.write('# the monster infobox "aggressive" and "max hit" fields (Kiyogitpy/osrs-wiki-data, July 2026) of the matching version.\n')
    f.write('# aggressive is blank unless the wiki says a plain Yes or No (wiki_text keeps conditions such as god items, N/A or\n')
    f.write('# Varies); max_hit is blank unless it is a single number. Generated by combat/generator/monster_aggression.py.\n')
    f.write('key\twiki_name\tversion\tlevel\taggressive\tmax_hit\twiki_text\n')
    for row in rows:
        f.write('\t'.join(row) + '\n')

if JAVA:
    yes = [r[0] for r in rows if r[4] == 'yes']
    no = [r[0] for r in rows if r[4] == 'no']

    def chunks(keys):
        lines, line = [], '            '
        for k in keys:
            item = '"%s", ' % k
            if len(line) + len(item) > 124:
                lines.append(line.rstrip())
                line = '            '
            line += item
        if line.strip():
            lines.append(line.rstrip())
        return '\n'.join(lines)

    with open(JAVA, encoding='utf-8') as f:
        src = f.read()
    gen = ('    // BEGIN GENERATED (combat/generator/monster_aggression.py)\n'
           '    private static final String[] AGGRESSIVE = {\n' + chunks(yes) + '\n    };\n'
           '    private static final String[] PASSIVE = {\n' + chunks(no) + '\n    };\n'
           '    // END GENERATED\n')
    src = re.sub(r'    // BEGIN GENERATED.*?    // END GENERATED\n', lambda m: gen, src, flags=re.S)
    with open(JAVA, 'w', encoding='utf-8') as f:
        f.write(src)

print('rows', len(rows), 'definite', sum(1 for r in rows if r[4]), 'max hits', sum(1 for r in rows if r[5]))
