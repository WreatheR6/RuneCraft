"""Writes src/test/resources/osrs/monster_retreat.tsv (round 43): every page of the OSRS Wiki category "Monsters that retreat when
low hitpoints" (Kiyogitpy/osrs-wiki-data) with the RuneCraft creatures that stand for it (the rows of monster_traits.tsv whose
wiki_name is that page, any version). MonsterAiTest locks MonsterAi.RETREATS against the keys. Usage:
    python3 -I monster_retreat.py <osrs-wiki-data> <monster_traits.tsv> <out.tsv>"""
import csv
import os
import sys

WIKI, TRAITS, OUT = sys.argv[1], sys.argv[2], sys.argv[3]
CATEGORY = '[[Category:Monsters that retreat when low hitpoints]]'

pages = []
with open(os.path.join(WIKI, 'index.tsv'), encoding='utf-8') as f:
    next(f)
    for line in f:
        parts = line.rstrip('\n').split('\t')
        if len(parts) < 2:
            continue
        path = os.path.join(WIKI, parts[1])
        try:
            with open(path, encoding='utf-8') as page:
                if CATEGORY in page.read():
                    pages.append(parts[0])
        except OSError:
            pass

keys = {}
with open(TRAITS, encoding='utf-8') as f:
    reader = csv.DictReader([l for l in f if not l.startswith('#')], delimiter='\t')
    for r in reader:
        keys.setdefault(r['wiki_name'], []).append(r['key'])

with open(OUT, 'w', encoding='utf-8') as f:
    f.write('# OSRS Wiki category "Monsters that retreat when low hitpoints" (Kiyogitpy/osrs-wiki-data, July 2026), one page a row,\n')
    f.write('# with the RuneCraft creatures standing for it (monster_traits.tsv rows of that wiki name; blank: none in RuneCraft).\n')
    f.write('# Generated by combat/generator/monster_retreat.py.\n')
    f.write('wiki_page\tkeys\n')
    for title in sorted(set(pages)):
        f.write(title + '\t' + ','.join(sorted(keys.get(title, []))) + '\n')

print('pages', len(set(pages)), 'with creatures', sum(1 for t in set(pages) if keys.get(t)))
