    /** True if cache tile (x, y) is floor in the plan. */
    static boolean floor(String[] rows, int x0, int top, int x, int y) {
        int j = top - y;
        int i = x - x0;
        return j >= 0 && j < rows.length && i >= 0 && i < rows[j].length() && rows[j].charAt(i) != '.';
    }
