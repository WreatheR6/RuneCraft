    private static void load(String data) {
        for (String line : data.split("\n")) {
            if (line.isBlank()) {
                continue;
            }
            String[] f = line.split("\\|");
            PRICES.put(f[0], new int[]{Integer.parseInt(f[1]), Integer.parseInt(f[2])});
        }
    }

    /** Guide price, or 0 if the item has no OSRS Grand Exchange price. */
    public static int guide(String id) {
        int[] p = PRICES.get(id);
        return p == null ? 0 : p[0];
    }

    /** Buy limit per 4 hours, or 0 if unknown/none. */
    public static int buyLimit(String id) {
        int[] p = PRICES.get(id);
        return p == null ? 0 : p[1];
    }

    public static boolean has(String id) {
        return PRICES.containsKey(id);
    }

